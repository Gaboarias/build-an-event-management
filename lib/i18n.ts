export type TKey = keyof typeof translations.es;

export function makeTr(lang: Lang) {
  return (key: TKey): string => translations[lang][key] as string;
}

export function getLang(): Lang {
  if (typeof window === 'undefined') return 'es';
  return (localStorage.getItem('wem-lang') as Lang) ?? 'es';
}

export function setLang(lang: Lang) {
  localStorage.setItem('wem-lang', lang);
}
